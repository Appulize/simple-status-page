#!/usr/bin/env node
// bin/vendor.mjs — copies pinned Preact + HTM ES module files to public/assets/vendor/
// Run: npm run vendor
// Output is committed to the repo; no Node required on the server.

import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root    = dirname(dirname(fileURLToPath(import.meta.url)));
const nm      = join(root, 'node_modules');
const out     = join(root, 'public', 'assets', 'vendor');
const outLic  = join(out, 'LICENSES');

mkdirSync(out,    { recursive: true });
mkdirSync(outLic, { recursive: true });

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

// Resolve the ESM module file for a given package name and candidate paths
function resolveModule(pkgName, candidates) {
    for (const rel of candidates) {
        const abs = join(nm, pkgName, rel);
        try {
            readFileSync(abs); // throws if missing
            return { abs, rel };
        } catch { /* try next */ }
    }
    throw new Error(`Cannot find ESM module for ${pkgName} (tried: ${candidates.join(', ')})`);
}

const copies = [
    {
        name:       'preact',
        candidates: ['dist/preact.module.js', 'src/index.js'],
        dest:       'preact.module.js',
        license:    'LICENSE',
    },
    {
        name:       'preact',
        candidates: ['hooks/dist/hooks.module.js', 'src/hooks.js'],
        dest:       'preact-hooks.module.js',
        license:    null, // same package, license already copied
    },
    {
        name:       'htm',
        candidates: ['dist/htm.module.js', 'src/index.mjs'],
        dest:       'htm.module.js',
        license:    'LICENSE',
    },
];

// htm/preact: a tiny adapter (preact import baked in) that htm ships
const htmPreactCandidates = [
    'preact/standalone.module.js',
    'preact/dist/htm-preact.module.js',
];

let htmPreactResolved = false;
for (const rel of htmPreactCandidates) {
    const abs = join(nm, 'htm', rel);
    try {
        readFileSync(abs);
        copyFileSync(abs, join(out, 'htm-preact.module.js'));
        console.log(`  htm/${rel} → htm-preact.module.js`);
        htmPreactResolved = true;
        break;
    } catch { /* try next */ }
}

if (!htmPreactResolved) {
    // Fallback: generate a thin wrapper that wires htm to preact ourselves
    const wrapper = `import { h, render, Fragment } from '/assets/vendor/preact.module.js';
import htm from '/assets/vendor/htm.module.js';
export const html = htm.bind(h);
export { h, render, Fragment };
`;
    writeFileSync(join(out, 'htm-preact.module.js'), wrapper);
    console.log('  generated htm-preact.module.js shim (htm/preact standalone not found)');
}

for (const entry of copies) {
    const { abs } = resolveModule(entry.name, entry.candidates);
    copyFileSync(abs, join(out, entry.dest));
    console.log(`  ${entry.name}/${entry.candidates[0]} → ${entry.dest}`);

    if (entry.license) {
        const licSrc = join(nm, entry.name, entry.license);
        try {
            copyFileSync(licSrc, join(outLic, `${entry.name}.LICENSE`));
        } catch {
            console.warn(`  warn: LICENSE not found for ${entry.name}`);
        }
    }
}

// Write a README with pinned versions
const versions = Object.fromEntries(
    ['preact', 'htm'].map(n => {
        const p = JSON.parse(readFileSync(join(nm, n, 'package.json'), 'utf8'));
        return [n, p.version];
    })
);

const readme = `# Vendored JS modules

These files are generated by \`npm run vendor\` and committed to the repo.
Do not edit manually. Re-run after bumping versions in package.json.

| File                    | Package  | Version  |
|-------------------------|----------|----------|
| preact.module.js        | preact   | ${versions.preact} |
| preact-hooks.module.js  | preact   | ${versions.preact} |
| htm.module.js           | htm      | ${versions.htm} |
| htm-preact.module.js    | htm      | ${versions.htm} |

## Updating

1. Edit \`package.json\` versions.
2. Run \`npm install && npm run vendor\`.
3. Commit the updated files in \`vendor/\`.
`;
writeFileSync(join(out, 'README.md'), readme);

console.log(`\nDone. Versions: preact@${versions.preact}, htm@${versions.htm}`);
